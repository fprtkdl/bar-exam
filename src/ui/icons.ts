/** 시계 방향 90° 회전 */
const rotate = (rows: string[]) => {
  const g = Array.from({ length: 16 }, (_, r) => (rows[r] ?? '').padEnd(16, '.'))
  return Array.from({ length: 16 }, (_, r) => Array.from({ length: 16 }, (_, c) => g[15 - c][r]).join(''))
}
const CHEVRON_LEFT = rotate(CHEVRON_DOWN)
const CHEVRON_RIGHT = rotate(rotate(CHEVRON_LEFT))

export const ICON_BITMAPS = { ...BITMAPS, 'chevron-left': CHEVRON_LEFT, 'chevron-right': CHEVRON_RIGHT } satisfies Record<
  string,
  string[]
>

export type IconName = keyof typeof ICON_BITMAPS

/** 칠한 칸을 가로 구간 단위 사각형 path 로 */
export function bitmapToPath(rows: string[]) {
  let d = ''
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`
  })
  return d
}
